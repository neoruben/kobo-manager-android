fun detectSystemLanguage(): String {
    val code = Locale.getDefault().language.lowercase()
    return if (SUPPORTED_LANGUAGES.containsKey(code)) code else "es"
}

fun tr(lang: String, key: String, vararg args: Pair<String, String>): String {
    val dict = TRANSLATIONS[lang] ?: TRANSLATIONS["en"]!!
    var text = dict[key] ?: TRANSLATIONS["en"]?.get(key) ?: key
    for ((k, v) in args) {
        text = text.replace("{$k}", v)
    }
    return text
}

fun formatSizeMb(bytes: Long): String {
    if (bytes <= 0L) return "0 MB"
    return String.format(Locale.US, "%.2f MB", bytes.toDouble() / (1024.0 * 1024.0))
}

fun detectTargetSlotForFilename(filename: String, defaultSlot: String = "dicthtml-es.zip"): String {
    val nl = filename.lowercase()
    return if (nl.startsWith("dicthtml") && nl.endsWith(".zip")) {
        nl
    } else {
        defaultSlot
    }
}
